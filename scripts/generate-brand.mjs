/** Rebuild the original OpenBricks SVG brand kit. No network or fonts required. */
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { createRequire } from 'node:module';

const root = fileURLToPath(new URL('../', import.meta.url));
const assets = path.join(root, 'docs/assets');
await mkdir(assets, { recursive: true });
await mkdir(path.join(root, 'web/lib'), { recursive: true });

// An open hexagonal brick with a separated top piece. The geometry is shared
// by the documentation kit, app component, and favicon through this generator.
const shapes = {
  body: 'M44 12 12 30.5v37L44 86l32-18.5V42L64 49v11.5L44 72 24 60.5v-23L44 26Z',
  face: 'M44 72 64 60.5V49l12-7v25.5L44 86Z',
  cap: 'm56 4 32 18.5-12 7L56 18Z',
};
const colors = { clay: '#D97757', ember: '#B74E33', oat: '#F1B788', ink: '#161C25', paper: '#F7F3EC', muted: '#AAB5C1' };
const mark = (mono = false) => `<path d="${shapes.body}" fill="${mono ? 'currentColor' : colors.clay}"/>${mono ? '' : `<path d="${shapes.face}" fill="${colors.ember}"/>`}<path d="${shapes.cap}" fill="${mono ? 'currentColor' : colors.oat}"/>`;
const svg = (width, height, title, body) => `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" role="img" aria-labelledby="title"><title id="title">${title}</title>${body}</svg>\n`;
const typeface = 'Arial, Helvetica, sans-serif';
const files = new Map();
files.set('openbricks-mark.svg', svg(96, 96, 'OpenBricks open brick logo', mark()));
files.set('openbricks-mark-mono.svg', svg(96, 96, 'OpenBricks monochrome logo', `<g color="${colors.ink}">${mark(true)}</g>`));
for (const theme of ['light', 'dark']) {
  const text = theme === 'dark' ? colors.paper : colors.ink;
  files.set(`openbricks-logo-${theme}.svg`, svg(600, 128, 'OpenBricks', `<g transform="translate(4 14)">${mark()}</g><text x="120" y="86" fill="${text}" font-family="${typeface}" font-size="68" font-weight="700" letter-spacing="-3">openbricks</text>`));
}

function banner(height) {
  const y = Math.round((height - 400) / 2);
  return svg(1200, height, 'OpenBricks — An open home for your data work.', `
  <defs><pattern id="grid" width="48" height="48" patternUnits="userSpaceOnUse"><path d="M48 0H0v48" fill="none" stroke="#293340" stroke-width="1"/></pattern><linearGradient id="fade"><stop stop-color="${colors.ink}"/><stop offset="1" stop-color="${colors.ink}" stop-opacity="0"/></linearGradient></defs>
  <rect width="1200" height="${height}" rx="20" fill="${colors.ink}"/>
  <rect x="660" width="540" height="${height}" fill="url(#grid)"/>
  <rect x="650" width="550" height="${height}" fill="url(#fade)"/>
  <g transform="translate(0 ${y})">
    <g transform="translate(58 35) scale(.65)">${mark()}</g>
    <text x="132" y="80" fill="${colors.paper}" font-family="${typeface}" font-size="38" font-weight="700" letter-spacing="-1.5">openbricks</text>
    <text x="64" y="180" fill="${colors.paper}" font-family="${typeface}" font-size="54" font-weight="700" letter-spacing="-1.8">An open home for</text>
    <text x="64" y="244" fill="${colors.oat}" font-family="${typeface}" font-size="54" font-weight="700" letter-spacing="-1.8">your data work.</text>
    <text x="66" y="292" fill="${colors.muted}" font-family="${typeface}" font-size="19">Notebooks. Spark SQL. Your infrastructure.</text>
    <g transform="translate(843 74) scale(2.4)">${mark()}</g>
    <path d="M778 153h-52v126h75m249-28h47v-96h-30" stroke="#44505C" stroke-width="1.5" fill="none"/>
    <circle cx="726" cy="153" r="4" fill="${colors.clay}"/><circle cx="1097" cy="155" r="4" fill="${colors.oat}"/>
    <text x="824" y="341" fill="${colors.muted}" font-family="${typeface}" font-size="12" letter-spacing="2">BUILD. RUN. MAKE IT YOURS.</text>
  </g>
  <text x="66" y="${height - 32}" fill="#85919F" font-family="${typeface}" font-size="11" letter-spacing="2">OPEN SOURCE · SELF-HOSTED · APACHE-2.0</text>`);
}
files.set('openbricks-banner.svg', banner(400));
files.set('openbricks-social.svg', banner(630));
for (const [name, content] of files) await writeFile(path.join(assets, name), content);

await writeFile(path.join(root, 'web/app/icon.svg'), svg(96, 96, 'OpenBricks', `<rect width="96" height="96" rx="22" fill="${colors.ink}"/><g transform="translate(9 6) scale(.82)">${mark()}</g>`));
await writeFile(path.join(root, 'web/lib/brand.ts'), `// Generated by scripts/generate-brand.mjs; edit the generator to change geometry.\nexport const brandShapes = ${JSON.stringify(shapes, null, 2)} as const;\nexport const brandTagline = "An open home for your data work.";\n`);
console.log(`Generated ${files.size} SVG brand assets, app favicon, and shared geometry.`);

if (process.argv.includes('--png')) {
  // Next.js includes sharp. Resolve it from web/ after running npm ci there.
  const require = createRequire(new URL('../web/package.json', import.meta.url));
  const sharp = require('sharp');
  for (const [name, content] of files) {
    const width = name.includes('mark') ? 1024 : 1200;
    await sharp(Buffer.from(content)).resize({ width }).png().toFile(path.join(assets, name.replace('.svg', '.png')));
  }
  console.log('Exported transparent PNG logos and 1200px GitHub banner/social images.');
}
